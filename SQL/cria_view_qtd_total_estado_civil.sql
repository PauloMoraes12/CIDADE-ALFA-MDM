-- CIDADE ALFA — MDM V2
-- View analítica: quantidade de cidadãos por estado civil

CREATE OR REPLACE VIEW VW_MDM_QTD_ESTADO_CIVIL AS
SELECT
    NM_ESTADO_CIVIL,
    COUNT(*) AS QTD_CIDADAOS
FROM T_MDM_CIDADAO
GROUP BY NM_ESTADO_CIVIL;

-- Consulta para validação da view
SELECT *
FROM VW_MDM_QTD_ESTADO_CIVIL
ORDER BY QTD_CIDADAOS DESC;