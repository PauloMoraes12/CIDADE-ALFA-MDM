-- CONSULTA EXECUTADA:

WITH DATAS_ORIGINAIS AS ( -- Reune as datas das fontes
    SELECT M.ID_GOLD_CIDADAO, -- Identifica o registro mestre
           P.DT_NASC_PREF AS DATA_PREFEITURA, -- Recupera a data da Prefeitura
           R.DT_NASCIMENTO AS DATA_RECEITA -- Recupera a data da Receita
    FROM T_MDM_CIDADAO M -- Consulta a tabela mestre
    LEFT JOIN T_SRC_PREFEITURA_CIDADAO P -- Relaciona a Prefeitura
           ON LPAD(TRIM(TO_CHAR(M.NR_CPF_CIDADAO)), 11, '0') = REGEXP_REPLACE(P.CPF_PREFEITURA, '[^0-9]', '') -- Normaliza e compara os CPFs
    LEFT JOIN T_SRC_RECEITA_FEDERAL R -- Relaciona a Receita
           ON LPAD(TRIM(TO_CHAR(M.NR_CPF_CIDADAO)), 11, '0') = REGEXP_REPLACE(R.CPF_RECEITA, '[^0-9]', '') -- Normaliza e compara os CPFs
    WHERE M.DT_NASCIMENTO IS NULL -- Seleciona os registros com data nula
) -- Encerra a consulta temporaria
SELECT ID_GOLD_CIDADAO, -- Identifica o cidadao
       DATA_PREFEITURA, -- Mostra a data original da Prefeitura
       DATA_RECEITA, -- Mostra a data original da Receita
       CASE -- Inicia a escolha da fonte
           WHEN TRIM(DATA_RECEITA) IS NOT NULL -- Verifica se a data da Receita esta preenchida
                AND VALIDATE_CONVERSION(TRIM(DATA_RECEITA) AS DATE, 'DD/MM/YYYY') = 1 THEN 'RECEITA' -- Prioriza a Receita quando valida
           WHEN TRIM(DATA_PREFEITURA) IS NOT NULL -- Verifica se a data da Prefeitura esta preenchida
                AND VALIDATE_CONVERSION(TRIM(DATA_PREFEITURA) AS DATE, 'MM/DD/YYYY') = 1 THEN 'PREFEITURA' -- Utiliza a Prefeitura como alternativa
           ELSE 'NENHUMA' -- Indica ausencia de data valida
       END AS FONTE_ESCOLHIDA, -- Nomeia a fonte escolhida
       CASE -- Inicia a simulacao da data
           WHEN TRIM(DATA_RECEITA) IS NOT NULL -- Verifica se a Receita possui data
                AND VALIDATE_CONVERSION(TRIM(DATA_RECEITA) AS DATE, 'DD/MM/YYYY') = 1 THEN TO_DATE(TRIM(DATA_RECEITA) DEFAULT NULL ON CONVERSION ERROR, 'DD/MM/YYYY') -- Converte a data da Receita
           WHEN TRIM(DATA_PREFEITURA) IS NOT NULL -- Verifica se a Prefeitura possui data
                AND VALIDATE_CONVERSION(TRIM(DATA_PREFEITURA) AS DATE, 'MM/DD/YYYY') = 1 THEN TO_DATE(TRIM(DATA_PREFEITURA) DEFAULT NULL ON CONVERSION ERROR, 'MM/DD/YYYY') -- Converte a data da Prefeitura
           ELSE NULL -- Mantem nulo se nao existir data valida
       END AS DATA_SIMULADA -- Nomeia a data simulada
FROM DATAS_ORIGINAIS -- Utiliza os dados reunidos
ORDER BY ID_GOLD_CIDADAO; -- Ordena pelo identificador

