-- ETAPA 11: COMPLEMENTO 01 - VERIFICACAO DOS RELACIONAMENTOS
-- DATA: 16/10/2026
-- ============================================================

-- OBJETIVO:
-- VERIFICAR SE OS CPFS DOS SEIS REGISTROS
-- FORAM ENCONTRADOS NAS FONTES ORIGINAIS.

-- CONSULTA EXECUTADA:
SELECT M.ID_GOLD_CIDADAO, -- Identifica o registro mestre
       CASE WHEN P.CPF_PREFEITURA IS NULL THEN 'NAO' ELSE 'SIM' END AS ENCONTROU_PREFEITURA, -- Verifica correspondencia na Prefeitura
       CASE WHEN R.CPF_RECEITA IS NULL THEN 'NAO' ELSE 'SIM' END AS ENCONTROU_RECEITA, -- Verifica correspondencia na Receita
       P.DT_NASC_PREF AS DATA_PREFEITURA, -- Exibe a data da Prefeitura
       R.DT_NASCIMENTO AS DATA_RECEITA -- Exibe a data da Receita
FROM T_MDM_CIDADAO M -- Consulta a tabela mestre
LEFT JOIN T_SRC_PREFEITURA_CIDADAO P -- Relaciona a Prefeitura
       ON TO_CHAR(M.NR_CPF_CIDADAO) = TRIM(P.CPF_PREFEITURA) -- Compara CPF como texto
LEFT JOIN T_SRC_RECEITA_FEDERAL R -- Relaciona a Receita
       ON TO_CHAR(M.NR_CPF_CIDADAO) = TRIM(R.CPF_RECEITA) -- Compara CPF como texto
WHERE M.DT_NASCIMENTO IS NULL -- Filtra registros com data nula
ORDER BY M.ID_GOLD_CIDADAO; -- Ordena os registros

