-- ANALISE:
-- O CPF DA TABELA MDM POSSUI TIPO NUMERICO.
-- OS CPFS DAS FONTES POSSUEM TIPO TEXTO.
-- A COMPARACAO DIRETA PODE PROVOCAR
-- CONVERSAO IMPLICITA DE TEXTO PARA NUMERO.
-- ESSA CONVERSAO PODE GERAR O ERRO ORA-01722.
-- A DIFERENCA DE TIPOS FOI CONFIRMADA.
-- A CAUSA DAS CORRESPONDENCIAS AUSENTES
-- AINDA PRECISA SER INVESTIGADA.

-- PONTO DE ATENCAO:
-- O TIPO NUMBER PODE PERDER ZEROS A ESQUERDA.
-- O TO_CHAR NAO RECUPERA ESSES ZEROS.
-- AS FONTES TAMBEM PODEM CONTER PONTUACAO.

-- EVIDENCIA:
