-- ============================================================
-- ETAPA 11: COMPARACAO DAS DATAS DE NASCIMENTO NAS FONTES
-- DATA: 16/10/2026
-- ============================================================

-- OBJETIVO:
-- COMPARAR AS DATAS DE NASCIMENTO DOS 6 REGISTROS
-- COM DATA NULA NO MDM COM AS FONTES ORIGINAIS.
-- INVESTIGAR SE EXISTEM DATAS QUE PODERIAM
-- TER SIDO APROVEITADAS PELA CARGA MDM V1.

-- PRIMEIRA TENTATIVA:
-- FOI EXECUTADA UMA CONSULTA COM LEFT JOIN
-- ENTRE A TABELA MDM, PREFEITURA E RECEITA FEDERAL.
-- OS RELACIONAMENTOS UTILIZARAM AS COLUNAS DE CPF.
-- A CONSULTA RETORNOU O ERRO ORA-01722.

-- ERRO IDENTIFICADO:
-- ORA-01722: NUMERO INVALIDO.

-- ANALISE DO ERRO:
-- O ORACLE TENTOU CONVERTER UM VALOR
-- DE TEXTO PARA NUMERO SEM SUCESSO.
-- A CONVERSAO IMPLICITA ENTRE OS CAMPOS
-- DE CPF FOI IDENTIFICADA COMO POSSIVEL CAUSA.
-- A CAUSA EXATA NAO FOI COMPROVADA NESTA TENTATIVA.

-- CORRECAO APLICADA:
-- FOI UTILIZADO TO_CHAR NO CPF DA TABELA MDM.
-- FOI UTILIZADO TRIM NOS CPFS DAS FONTES.
-- O OBJETIVO FOI COMPARAR OS VALORES COMO TEXTO
-- E EVITAR A CONVERSAO IMPLICITA PARA NUMERO.

-- CONSULTA CORRIGIDA E EXECUTADA:
SELECT M.ID_GOLD_CIDADAO, -- Identifica o registro mestre
       P.DT_NASC_PREF AS DATA_PREFEITURA, -- Exibe a data original da Prefeitura
       R.DT_NASCIMENTO AS DATA_RECEITA, -- Exibe a data original da Receita Federal
       M.DT_NASCIMENTO AS DATA_MDM, -- Exibe a data gravada no MDM
       M.FL_DIVERGENCIA -- Exibe o indicador de divergencia
FROM T_MDM_CIDADAO M -- Consulta a tabela mestre
LEFT JOIN T_SRC_PREFEITURA_CIDADAO P -- Relaciona a Prefeitura
       ON TO_CHAR(M.NR_CPF_CIDADAO) = TRIM(P.CPF_PREFEITURA) -- Compara os CPFs como texto
LEFT JOIN T_SRC_RECEITA_FEDERAL R -- Relaciona a Receita Federal
       ON TO_CHAR(M.NR_CPF_CIDADAO) = TRIM(R.CPF_RECEITA) -- Compara os CPFs como texto
WHERE M.DT_NASCIMENTO IS NULL -- Seleciona os registros sem data
ORDER BY M.ID_GOLD_CIDADAO; -- Ordena pela chave mestre

-- RESULTADO OBTIDO:
-- A CONSULTA CORRIGIDA EXECUTOU SEM ERROS.
-- TOTAL DE LINHAS RETORNADAS: 6.
-- ID_GOLD_CIDADAO: 1, 9, 28, 58, 76 E 78.
-- DATA_PREFEITURA: NULL NOS 6 RESULTADOS.
-- DATA_RECEITA: NULL NOS 6 RESULTADOS.
-- DATA_MDM: NULL NOS 6 RESULTADOS.
-- FL_DIVERGENCIA: SIM NOS 6 RESULTADOS.

-- ANALISE DO RESULTADO:
-- A CONSULTA RETORNOU OS 6 REGISTROS ESPERADOS.
-- ENTRETANTO, OS VALORES NULL DAS FONTES
-- NAO COMPROVAM QUE AS DATAS ESTEJAM AUSENTES.
-- O LEFT JOIN TAMBEM RETORNA NULL QUANDO
-- NAO ENCONTRA CORRESPONDENCIA ENTRE OS CPFS.
-- PORTANTO, FOI NECESSARIO INVESTIGAR
