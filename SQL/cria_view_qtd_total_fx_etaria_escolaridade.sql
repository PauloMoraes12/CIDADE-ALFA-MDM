-- CIDADE ALFA — MDM V2
-- View analítica: quantidade de cidadãos por faixa etária e escolaridade

CREATE OR REPLACE VIEW VW_MDM_QTD_FX_ETARIA_ESCOLARIDADE AS
SELECT
    NM_FAIXA_ETARIA,
    NM_ESCOLARIDADE,
    COUNT(*) AS QTD_CIDADAOS
FROM T_MDM_CIDADAO
GROUP BY
    NM_FAIXA_ETARIA,
    NM_ESCOLARIDADE;

-- Consulta para validação da view
SELECT *
FROM VW_MDM_QTD_FX_ETARIA_ESCOLARIDADE
ORDER BY QTD_CIDADAOS DESC;
